// Optional one-time owner evidence, never a default browser-suite prerequisite.
// From the checkout root:
// DOCS_ALIGNMENT_PRESERVATION_MANIFEST=/path/approved.json \
// DOCS_ALIGNMENT_EVIDENCE_DIRECTORY=/path/evidence node apps/website/src/components/docs/tests/Alignment.browser.mjs
// The JSON must contain baseTree (40 hex), provenance (approval/archive description),
// landingReadOnlyManifest (the original 21 relative source paths -> SHA256), and
// screenshots: { "1440": { full: { path, sha256 }, hero: { path, sha256 } }, "390": ... }.
// Image paths resolve relative to the JSON file; absolute archived paths also work.
// Supply approved BEFORE images/digests, not captures generated by the run under test.
import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import { createHash } from "node:crypto"
import { dirname, extname, resolve } from "node:path"

const landingFiles = [
  "Content.ts",
  "Landing.css",
  "LandingExample.ts",
  "LandingStyles.ts",
  "Playback.astro",
  "Playback.css",
  "Playback.ts",
  "PlaybackClock.ts",
  "Postgres.astro",
  "Rows.css",
  "Storyboard.ts",
  "System.astro",
  "System.tsx",
  "Walkthrough.css",
  "tests/Browser.mjs",
  "tests/Content.mjs",
  "tests/Controls.browser.mjs",
  "tests/Docs.browser.mjs",
  "tests/PlaybackClock.test.mjs",
  "tests/Rows.browser.mjs"
].map((file) => "apps/website/src/components/landing/" + file)
landingFiles.push("apps/website/src/pages/index.astro")
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex")
const hashPattern = /^[a-f0-9]{64}$/i
const isRecord = (value) =>
  value !== null && typeof value === "object" && !Array.isArray(value)
const required = async (path, purpose) => {
  try {
    return await readFile(path)
  } catch (cause) {
    throw new Error(
      `Requested owner preservation: cannot read ${purpose} at ${path}. Supply the approved input described in Preservation.mjs.`,
      { cause }
    )
  }
}

export async function readOwnerPreservation(inputPath) {
  const path = resolve(inputPath)
  const bytes = await required(path, "reference manifest")
  let input
  try {
    input = JSON.parse(bytes.toString())
  } catch (cause) {
    throw new Error(
      `Requested owner preservation: manifest ${path} must be valid JSON (see Preservation.mjs).`,
      { cause }
    )
  }
  assert(isRecord(input), "Requested owner preservation: manifest must be a JSON object")
  assert(
    typeof input.baseTree === "string" && /^[a-f0-9]{40}$/i.test(input.baseTree),
    "Requested owner preservation: baseTree must identify the approved source tree"
  )
  assert(
    typeof input.provenance === "string" && input.provenance.trim(),
    "Requested owner preservation: provenance must describe the approval/archive"
  )
  assert(
    isRecord(input.landingReadOnlyManifest),
    "Requested owner preservation: landingReadOnlyManifest is required"
  )
  assert.deepEqual(
    Object.keys(input.landingReadOnlyManifest).sort(),
    [...landingFiles].sort(),
    "Requested owner preservation: supply the original complete 21-file landing manifest"
  )
  const sourceChecks = []
  for (const file of landingFiles) {
    const expected = input.landingReadOnlyManifest[file]
    assert(
      typeof expected === "string" && hashPattern.test(expected),
      `Requested owner preservation: invalid SHA256 for ${file}`
    )
    const actual = digest(await required(resolve(file), "landing source"))
    assert.equal(
      actual,
      expected.toLowerCase(),
      `Requested owner preservation: landing source mismatch for ${file}`
    )
    sourceChecks.push({ file, expected: expected.toLowerCase(), actual })
  }
  const screenshots = {}
  for (const width of [1440, 390]) {
    screenshots[width] = {}
    for (const kind of ["full", "hero"]) {
      const reference = input.screenshots?.[width]?.[kind]
      assert(
        isRecord(reference) &&
          typeof reference.path === "string" &&
          reference.path &&
          typeof reference.sha256 === "string" &&
          hashPattern.test(reference.sha256),
        `Requested owner preservation: screenshots.${width}.${kind} needs an approved PNG path and SHA256`
      )
      const referencePath = resolve(dirname(path), reference.path)
      assert.equal(
        extname(referencePath).toLowerCase(),
        ".png",
        `Requested owner preservation: ${width} ${kind} reference must be a PNG`
      )
      const image = await required(referencePath, `${width} ${kind} approved PNG`)
      assert(
        image.length >= 24 &&
          image.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])),
        `Requested owner preservation: malformed PNG at ${referencePath}`
      )
      const actual = digest(image)
      assert.equal(
        actual,
        reference.sha256.toLowerCase(),
        `Requested owner preservation: approved PNG digest mismatch at ${referencePath}`
      )
      screenshots[width][kind] = { path: referencePath, sha256: actual }
    }
  }
  return {
    manifest: {
      path,
      sha256: digest(bytes),
      baseTree: input.baseTree,
      provenance: input.provenance
    },
    sourceChecks,
    screenshots
  }
}

export async function compareOwnerLanding(preservation, width, captures) {
  const comparison = { width }
  for (const kind of ["full", "hero"]) {
    const reference = preservation.screenshots[width][kind]
    const actual = digest(
      await required(captures[kind], `${width} ${kind} current capture`)
    )
    assert.equal(
      actual,
      reference.sha256,
      `Requested owner preservation: ${width} ${kind} capture mismatch against approved ${reference.path}`
    )
    comparison[kind] = {
      reference: reference.path,
      expectedSha256: reference.sha256,
      currentCapture: captures[kind],
      currentSha256: actual
    }
  }
  return comparison
}
